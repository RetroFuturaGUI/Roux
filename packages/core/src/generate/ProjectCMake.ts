import type { PlatformSettings, ProjectValues } from "@retrofuturagui/roux-protocol";
import { compilerFlags, flagLanguages } from "../project/Catalog.js";
import { defaultPlatformSettings } from "../project/ProjectFile.js";
import type { RegionContent } from "./CMakeRegions.js";

export const projectCMakePath = "source/generated/Project.cmake";

//The value TestProject's CMakeLists.txt takes in LANG for the steps after a binding's library is built.
const bindingLanguages: Record<string, string> = { "C#": "CSharp", "Python": "Python", "Rust": "Rust" };

//What Generate found in the project's folders, relative to it with /.
export interface ProjectFiles
{
    readonly sources: readonly string[]; //Roux's, in source/generated/; CMake finds the ones in source/code/ itself.
    readonly includeDirectories: readonly string[]; //source, source/generated, source/code and Roux's folders with headers.
    readonly assetFolders: readonly string[]; //The asset folders that exist, in the Project's order.
}

export const sourceExtensions = [".cpp", ".cc", ".cxx", ".c"];
export const headerExtensions = [".hpp", ".hh", ".hxx", ".h"];
//Folders that hold another tool's output or files, never the project's C++. Hidden folders are skipped too.
export const skippedFolders = ["bin", "obj", "out", "build", "target", "node_modules", "__pycache__"];

const sourcePatterns = sourceExtensions.map(extension => "*" + extension);
const headerPatterns = headerExtensions.map(extension => "*" + extension);
//A path relative to source/code/ inside a hidden or skipped folder; written as CMake reads it inside quotes.
const skippedFolderExpression = "(^|/)(\\\\.[^/]*|" + skippedFolders.join("|") + ")/";

//A quoted CMake argument holding text as it is: no variable, no list separator, no escape is read from it.
export function cmakeString(text: string): string
{
    return "\"" + text.replace(/[\\"$;]/g, character => "\\" + character) + "\"";
}

function projectPath(relative: string): string
{
    return "\"${PROJECT_SOURCE_DIR}/" + cmakeString(relative).slice(1);
}

//Only C++23 and newer include RetroFuturaGUI's headers; every other language goes through its C interface, built as a
//shared library (.bechaml plan, 3.1). The library and the generated code stay C++23 either way.
export function isSharedLibrary(settings: PlatformSettings): boolean
{
    return "C++" !== settings.language || 23 > Number(settings.standard);
}

//The platform's compiler flags as one kind of compiler writes them; none for a language CMake doesn't compile.
function compileOptions(settings: PlatformSettings, kind: "msvc" | "gnu"): string
{
    if (!flagLanguages.includes(settings.language))
        return "";

    return settings.compilerFlags.flatMap(flag => compilerFlags[flag]?.[kind] ?? []).join(" ");
}

//source/generated/Project.cmake, generated whole: what each platform builds, the library's options and the files.
export function projectCMakeText(values: ProjectValues, files: ProjectFiles): string
{
    const lines =
    [
        "# Generated by Roux from Project.bechaml. Changes here are lost on the next Generate.",
        "",
        "# The platform being built. Roux passes it; a configure without Roux takes this computer's.",
        "if(NOT DEFINED ROUX_PLATFORM)",
        "    if(WIN32)",
        "        set(ROUX_PLATFORM \"Windows\")",
        "    elseif(APPLE)",
        "        set(ROUX_PLATFORM \"macOS\")",
        "    else()",
        "        set(ROUX_PLATFORM \"Linux\")",
        "    endif()",
        "endif()",
        ""
    ];

    for (const [index, platform] of values.platforms.entries())
    {
        const settings = values.platformSettings[platform] ?? defaultPlatformSettings(platform);
        const cxxStandard = "C++" === settings.language && 26 <= Number(settings.standard) ? settings.standard : "23";

        lines.push(
            (0 === index ? "if" : "elseif") + "(ROUX_PLATFORM STREQUAL " + cmakeString(platform) + ")",
            "    set(ROUX_LANGUAGE " + cmakeString(settings.language) + ")",
            "    set(ROUX_LANGUAGE_STANDARD " + cmakeString(settings.standard) + ")",
            "    set(ROUX_DYNLIB " + (isSharedLibrary(settings) ? "ON" : "OFF") + ")",
            "    set(LANG " + cmakeString(bindingLanguages[settings.language] ?? "") + ")",
            "    set(CMAKE_CXX_STANDARD " + cxxStandard + ")",
            "    set(ROUX_COMPILE_OPTIONS_MSVC " + compileOptions(settings, "msvc") + ")",
            "    set(ROUX_COMPILE_OPTIONS_GNU " + compileOptions(settings, "gnu") + ")");
    }

    lines.push(
        "else()",
        "    message(FATAL_ERROR \"Project.bechaml doesn't list the platform ${ROUX_PLATFORM}. It lists " + values.platforms.join(", ") + ".\")",
        "endif()",
        "",
        "# The compiler flags ticked in the Project tab, as the configured compiler writes them: clang-cl takes MSVC's.",
        "if(CMAKE_CXX_COMPILER_FRONTEND_VARIANT STREQUAL \"MSVC\")",
        "    set(ROUX_COMPILE_OPTIONS ${ROUX_COMPILE_OPTIONS_MSVC})",
        "else()",
        "    set(ROUX_COMPILE_OPTIONS ${ROUX_COMPILE_OPTIONS_GNU})",
        "endif()",
        "",
        "set(CMAKE_CXX_STANDARD_REQUIRED ON)",
        "set(CMAKE_CXX_EXTENSIONS OFF)",
        "",
        "# The C interface's exports, for the library and the generated code alike.",
        "set(DYNLIB_MODE ${ROUX_DYNLIB})",
        "",
        "if(ROUX_DYNLIB)",
        "    add_compile_definitions(DYNLIB_MODE)",
        "    message(STATUS \"Roux: ${ROUX_PLATFORM}, ${ROUX_LANGUAGE} ${ROUX_LANGUAGE_STANDARD}, a shared library for the C interface\")",
        "else()",
        "    message(STATUS \"Roux: ${ROUX_PLATFORM}, ${ROUX_LANGUAGE} ${ROUX_LANGUAGE_STANDARD}, a program\")",
        "endif()",
        "",
        "# RetroFuturaGUI's options. Plain variables win over the options' defaults and over values cached by earlier configures.",
        "set(RETROFUTURAGUI_TRACKER_MODULES " + (values.features.includes("TrackerModules") ? "ON" : "OFF") + ")",
        "set(RETROFUTURAGUI_ROYALTY_FREE_CODECS_ONLY " + (values.allowNonRoyaltyFreeCodecs ? "OFF" : "ON") + ")",
        //Feature names are from a fixed list, so the ; between them stays a list separator.
        "set(ROUX_FEATURES \"" + values.features.join(";") + "\")",
        "",
        "# The project's own files are found while building, so a new one needs no Generate. Hidden folders and other",
        "# tools' output (a C# project's bin/ and obj/, ...) are left out.",
        "file(GLOB_RECURSE ROUX_CODE_SOURCES CONFIGURE_DEPENDS RELATIVE \"${PROJECT_SOURCE_DIR}/source/code\"",
        ...sourcePatterns.map(pattern => "    \"${PROJECT_SOURCE_DIR}/source/code/" + pattern + "\""),
        ")",
        "file(GLOB_RECURSE ROUX_CODE_HEADERS CONFIGURE_DEPENDS RELATIVE \"${PROJECT_SOURCE_DIR}/source/code\"",
        ...headerPatterns.map(pattern => "    \"${PROJECT_SOURCE_DIR}/source/code/" + pattern + "\""),
        ")",
        "list(FILTER ROUX_CODE_SOURCES EXCLUDE REGEX \"" + skippedFolderExpression + "\")",
        "list(FILTER ROUX_CODE_HEADERS EXCLUDE REGEX \"" + skippedFolderExpression + "\")",
        "list(TRANSFORM ROUX_CODE_SOURCES PREPEND \"${PROJECT_SOURCE_DIR}/source/code/\")",
        "",
        "# Roux's own files are listed, since only Generate adds them.",
        "set(ROUX_SOURCES",
        ...files.sources.map(source => "    " + projectPath(source)),
        "    ${ROUX_CODE_SOURCES}",
        ")",
        "",
        "# Every folder holding headers, so they're included by their names.",
        "set(ROUX_INCLUDE_DIRECTORIES",
        ...files.includeDirectories.map(directory => "    " + projectPath(directory)),
        ")",
        "",
        "foreach(header IN LISTS ROUX_CODE_HEADERS)",
        "    get_filename_component(directory \"${PROJECT_SOURCE_DIR}/source/code/${header}\" DIRECTORY)",
        "    list(APPEND ROUX_INCLUDE_DIRECTORIES \"${directory}\")",
        "endforeach()",
        "",
        "list(REMOVE_DUPLICATES ROUX_INCLUDE_DIRECTORIES)",
        "");

    return lines.join("\n");
}

//What Roux writes into CMakeLists.txt's regions, in the order they belong.
export function cmakeRegions(values: ProjectValues, files: ProjectFiles): RegionContent[]
{
    const target = cmakeString(values.name);
    const assetsTarget = cmakeString(values.name + "Assets");
    const output = "$<TARGET_FILE_DIR:" + values.name + ">";
    const copy = (from: string, to: string) => [
        "    COMMAND ${CMAKE_COMMAND} -E ${ROUX_COPY_DIRECTORY}",
        "        \"${CMAKE_CURRENT_SOURCE_DIR}/" + cmakeString(from).slice(1),
        "        \"" + output + "/" + to + "\""
    ];

    return [
        {
            name: "project",
            description: "Rewritten on every Generate. Change Project.bechaml Instead!!1!",
            lines:
            [
                "cmake_minimum_required(VERSION " + values.cmakeVersion + ")",
                "project(" + target + " VERSION " + values.version + ")",
                "include(\"${CMAKE_CURRENT_SOURCE_DIR}/" + projectCMakePath + "\")"
            ]
        },
        {
            name: "target",
            description: "Rewritten on every Generate. The files come from source/code/ and source/generated/",
            lines:
            [
                "if(ROUX_DYNLIB)",
                "    add_library(" + target + " SHARED ${ROUX_SOURCES})",
                "    set_target_properties(" + target + " PROPERTIES OUTPUT_NAME " + cmakeString(values.name + "Native") + ")",
                "else()",
                "    add_executable(" + target + " ${ROUX_SOURCES})",
                "endif()",
                "",
                "target_include_directories(" + target + " PRIVATE ${ROUX_INCLUDE_DIRECTORIES})",
                "target_compile_options(" + target + " PRIVATE ${ROUX_COMPILE_OPTIONS})"
            ]
        },
        {
            name: "library",
            description: "Rewritten on every Generate.",
            lines:
            [
                "# The same flags reach RetroFuturaGUI and what it builds, which set none of their own",
                "add_compile_options(${ROUX_COMPILE_OPTIONS})",
                "add_subdirectory(\"${CMAKE_CURRENT_SOURCE_DIR}/RetroFuturaGUI\")",
                "target_link_libraries(" + target + " PRIVATE \"RetroFuturaGUI\")"
            ]
        },
        {
            name: "assets",
            description: "Rewritten on every Generate. The asset folders are listed in Project.bechaml.",
            lines:
            [
                "# Copied on every build, after the program, so a changed asset or shader arrives even when the program isn't rebuilt",
                "if(CMAKE_VERSION VERSION_GREATER_EQUAL 3.26)",
                "    set(ROUX_COPY_DIRECTORY copy_directory_if_different)",
                "else()",
                "    set(ROUX_COPY_DIRECTORY copy_directory)",
                "endif()",
                "",
                "add_custom_target(" + assetsTarget + " ALL",
                ...copy("RetroFuturaGUI/source/Shaders/ShaderSource", "ShaderSource"),
                ...copy("RetroFuturaGUI/Resources", "Resources"),
                ...files.assetFolders.flatMap(folder => copy(folder, "Assets")),
                "    VERBATIM",
                ")",
                "add_dependencies(" + assetsTarget + " " + target + ")"
            ]
        }
    ];
}