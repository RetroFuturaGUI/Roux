//What the scene and window generators share: an element's attributes and parts as calls looked up in Schema.json, values
//as C++ of the type they go to, problems at the .bechaml's line and column, and C++ with #line back to the markup.

//The first line of every C++ file Roux generates. A file in source/generated/ without it isn't overwritten.
export const generatedMark = "//Generated by Roux";

//One line of C++ and the .bechaml line it comes from; none for lines that come from no markup.
export interface Statement
{
    readonly text: string;
    readonly line?: number;
}

//A <Slot>.
export interface SlotDeclaration
{
    readonly name: string;
    readonly returnType: string;
    readonly params: string;
    readonly paramCount: number;
    readonly isAsync: boolean;
}

//What the user's class files are made from, and what they hold now: undefined when they don't exist yet.
export interface UserClass
{
    readonly name: string;
    readonly namespace: string;
    readonly constructor: string; //The public constructor's line.
    readonly slots: readonly SlotDeclaration[];
    readonly header: string | undefined;
    readonly source: string | undefined;
    readonly folder: string; //Where they go, absolute.
}

//A value that can't be written as the C++ type it goes to. It's reported where the value is.
export class ConversionError extends Error
{
    constructor(readonly node: Span | undefined, message: string)
    {
        super(message);
    }
}

export const cppKeywords = new Set(["alignas", "alignof", "and", "asm", "auto", "bool", "break", "case", "catch", "char", "class", "const", "consteval", "constexpr", "constinit", "continue", "decltype", "default", "delete", "do", "double", "else", "enum", "explicit", "export", "extern", "false", "float", "for", "friend", "goto", "if", "inline", "int", "long", "mutable", "namespace", "new", "noexcept", "not", "nullptr", "operator", "or", "private", "protected", "public", "register", "requires", "return", "short", "signed", "sizeof", "static", "struct", "switch", "template", "this", "throw", "true", "try", "typedef", "typeid", "typename", "union", "unsigned", "using", "virtual", "void", "volatile", "while", "xor"]);

const growingGlowOwners = new Set(["RetroFuturaGUI::Border", "RetroFuturaGUI::Background"]);
const isEmitSignal = (parameter: SchemaParameter) => "emitSignal" === parameter.name && "bool" === parameter.type;

//A parameter naming a file the library loads, such as SetImage(path) or an SvgImage's SvgImagePath
const isFileParameter = (type: string, name: string) => ("std::string_view" === type || "std::string" === type) && /path$/i.test(name);

const isFile = (file: string) => existsSync(file) && statSync(file).isFile();
const unsignedTypes = new Set(["u8", "u16", "u32", "u64", "uSize"]);
export const integerTypes = new Set([...unsignedTypes, "i8", "i16", "i32", "i64", "int"]);

//The value types Type="…" picks for a widget whose setters are templates (a Slider's MinValue and Value), as C++ types
export const valueTypes: Readonly<Record<string, string>> = { I8: "i8", I16: "i16", I32: "i32", I64: "i64", U8: "u8", U16: "u16", U32: "u32", U64: "u64", F32: "f32", F64: "f64" };

export abstract class MarkupGenerator
{
    protected readonly _file: string; //The .bechaml, absolute.
    protected readonly _folder: string; //The project's.
    protected readonly _schema: Schema;
    protected readonly _problems: GenerateProblem[] = [];
    protected readonly _headers = new Set<string>(); //Library headers by name, and standard ones as <array>.
    protected readonly _files = new Map<string, AssetKind | undefined>(); //The files the markup names, as the built app finds them.
    private readonly _assetFolders: readonly string[]; //The project's, relative to it, in the order files are looked up.
    private readonly _lineMap: LineMap;

    constructor(file: string, text: string, folder: string, schema: Schema, assetFolders: readonly string[])
    {
        this._file = file;
        this._folder = folder;
        this._schema = schema;
        this._assetFolders = assetFolders;
        this._lineMap = new LineMap(text);
    }

    //The function a signal calls for one of its targets (Slots.X and so on), or undefined after reporting why not.
    protected abstract connection(value: Value, argumentCount: number): { lambda: string; isAsync: boolean } | undefined;

    //Problems

    protected error(node: Span | undefined, message: string): void
    {
        this.report(node, "error", message);
    }

    protected report(node: Span | undefined, severity: GenerateProblem["severity"], message: string): void
    {
        const position = this._lineMap.position(node?.start ?? 0);
        this._problems.push({ file: this._file, line: position.line, column: position.column, severity: severity, message: message });
    }

    protected hasErrors(): boolean
    {
        return this._problems.some(problem => "error" === problem.severity);
    }

    protected lineOf(node: Span): number
    {
        return this._lineMap.position(node.start).line;
    }

    protected markupPath(): string
    {
        return path.relative(this._folder, this._file).split(path.sep).join("/");
    }

    //The element's name, checked to be one a C++ class can take and to match its file's.
    protected readClassName(root: Element, kind: string): string | undefined
    {
        const nameValue = root.attributes.find(attribute => "Name" === attribute.name)?.value;
        const name = "String" === nameValue?.kind ? nameValue.value : undefined;
        const stem = path.basename(this._file, path.extname(this._file));

        if (!name)
        {
            this.error(root, "<" + kind + "> needs a Name, written as a string: Name=\"" + stem + "\".");
            return undefined;
        }

        if (name !== stem)
        {
            this.error(root, "The " + kind.toLowerCase() + " is named " + name + ", but its file " + stem + ".bechaml: the two have to match.");
            return undefined;
        }

        if (!/^[A-Za-z_]\w*$/.test(name) || cppKeywords.has(name))
        {
            this.error(root, name + " can't name a C++ class.");
            return undefined;
        }

        return name;
    }

    //<Slot Async>void Save()</Slot>: a C++ function's signature, and whether it runs on its own thread.
    protected readSlot(element: Element, declared: ReadonlyMap<string, SlotDeclaration>): SlotDeclaration | undefined
    {
        const signature = element.rawText?.text.trim() ?? "";
        const match = /^(?:(.+?)\s+)?([A-Za-z_]\w*)\s*\(([^()]*)\)$/.exec(signature);

        if (!match?.[2])
        {
            this.error(element, "A slot is written as a C++ function, such as <Slot>void Accept()</Slot>.");
            return undefined;
        }

        const name = match[2];
        const params = (match[3] ?? "").trim();

        if (declared.has(name))
        {
            this.error(element, "The slot " + name + " is declared twice.");
            return undefined;
        }

        for (const attribute of element.attributes.filter(attribute => "Async" !== attribute.name))
            this.error(attribute, "A slot takes only Async.");

        return {
            name: name,
            returnType: match[1]?.trim() ?? "void",
            params: params,
            paramCount: "" === params || "void" === params ? 0 : splitTopLevel(params).length,
            isAsync: element.attributes.some(attribute => "Async" === attribute.name && (!attribute.value || ("Bool" === attribute.value.kind && attribute.value.value)))
        };
    }

    //The user's class files, next to the .bechaml: made once, then the header gets the declarations of slots it lacks,
    //under its privateSlots: label, and the source an empty body for each. A slot that loads a scene starts out loading
    //it. Only files that change are returned.
    protected userFiles(user: UserClass): Map<string, string>
    {
        const files = new Map<string, string>();
        const header = this.userHeaderText(user);
        const source = this.userSourceText(user);

        if (undefined !== header)
            files.set(path.join(user.folder, user.name + ".hpp"), header);

        if (undefined !== source)
            files.set(path.join(user.folder, user.name + ".cpp"), source);

        return files;
    }

    private userHeaderText(user: UserClass): string | undefined
    {
        const declaration = (slot: SlotDeclaration) => slot.returnType + " " + slot.name + "(" + slot.params + ") override;";

        if (undefined === user.header)
        {
            return [
                "#pragma once",
                "#include \"" + user.name + "_p.hpp\"",
                "",
                "namespace " + user.namespace,
                "{",
                "    class " + user.name + " final : public " + user.name + "_p",
                "    {",
                "    public:",
                "        " + user.constructor,
                "",
                "    privateSlots:",
                ...user.slots.map(slot => "        " + declaration(slot)),
                "    };",
                "}",
                ""
            ].join("\n");
        }

        const existing = user.header;
        const missing = user.slots.filter(slot => !new RegExp("\\b" + slot.name + "\\s*\\(").test(existing));

        if (0 === missing.length)
            return undefined;

        const newline = existing.includes("\r\n") ? "\r\n" : "\n";
        const lines = existing.split(/\r?\n/);
        const label = lines.findIndex(line => /^\s*privateSlots\s*:\s*$/.test(line));

        if (-1 === label)
        {
            this._problems.push({ file: path.join(user.folder, user.name + ".hpp"), line: 1, column: 1, severity: "warning", message: "The class has no privateSlots: label, so Roux didn't declare " + missing.map(slot => slot.name).join(", ") + "." });
            return undefined;
        }

        const indent = /^\s*/.exec(lines[label + 1] ?? "")?.[0] || "        ";
        lines.splice(label + 1, 0, ...missing.map(slot => indent + declaration(slot)));
        return lines.join(newline);
    }

    private userSourceText(user: UserClass): string | undefined
    {
        const existing = user.source;
        const qualified = user.namespace + "::" + user.name;
        const slots = user.slots.filter(slot => undefined === existing || !new RegExp("::" + slot.name + "\\s*\\(").test(existing));

        if (undefined !== existing && 0 === slots.length)
            return undefined;

        const stubs = slots.flatMap(slot =>
        [
            "",
            slot.returnType + " " + qualified + "::" + slot.name + "(" + slot.params.replace(/\s*=[^,]*/g, "") + ")",
            "{",
            ...("void" === slot.returnType ? [] : ["    return {};"]),
            "}"
        ]);

        if (undefined === existing)
            return ["#include \"" + user.name + ".hpp\"", ...stubs, ""].join("\n");

        const newline = existing.includes("\r\n") ? "\r\n" : "\n";
        return existing.replace(/(\r?\n)*$/, "") + newline + stubs.join(newline) + newline;
    }

    //Aesthetic=Aesthetics.ColorfulPop names the Aesthetic; whether it exists is the styles' check.
    protected aestheticStatements(attribute: Attribute, target: string): Statement[]
    {
        const value = attribute.value;
        let name: string | undefined;

        if ("Reference" === value?.kind && 2 === value.segments.length && "Aesthetics" === value.segments[0])
            name = value.segments[1];
        else if ("String" === value?.kind)
            name = value.value;

        if (undefined === name)
        {
            this.error(value ?? attribute, "Aesthetic names one: Aesthetic=Aesthetics.ColorfulPop.");
            return [];
        }

        return [{ text: target + "SetAesthetic(" + JSON.stringify(name) + ");", line: this.lineOf(attribute) }];
    }

    //A part's values and its own parts: <Indicator><Background Colors=…/></Indicator> is GetIndicator().GetBackground().
    //ownerOwner holds the owner when the owner is a part itself, as a glow's Border holds the glow of a <Flash>
    protected partStatements(owner: SchemaClass, element: Element, target: string, ownerOwner?: SchemaClass): Statement[]
    {
        const part = owner.parts[element.name];
        const partClass = part ? this._schema.classes[part.type] : undefined;

        if (!part || !partClass)
            return [];

        if (element.value)
            this.error(element.value, "A part holds values as attributes, not as its text.");

        if ("Flash" === part.type)
            this.checkFlash(element, ownerOwner);

        const partTarget = target + part.getter + "().";
        const statements = this.attributeStatements(partClass, element.name, element.attributes, partTarget);

        for (const child of element.elements)
        {
            if (!partClass.parts[child.name])
            {
                this.error(child, child.name + " isn't a part of " + element.name + ".");
                continue;
            }

            statements.push(...this.partStatements(partClass, child, partTarget, owner));
        }

        return statements;
    }

    //A flash's steps, loop and times have to fit together (.bechaml/Plan.md 2.6). Lists given by reference aren't counted
    private checkFlash(element: Element, glowOwner: SchemaClass | undefined): void
    {
        const find = (name: string) => element.attributes.find(attribute => name === attribute.name);
        const opacities = find("Opacities");
        const widths = find("Widths");

        if (!opacities)
        {
            this.error(element, "A <Flash> needs Opacities, one per step: Opacities={ 1.0, 0.0 }.");
            return;
        }

        if (widths && !growingGlowOwners.has(glowOwner?.cpp ?? ""))
            this.error(widths, "Only the glows of a Border and a Background grow, so this <Flash> takes no Widths.");

        if ("List" !== opacities.value?.kind)
            return;

        const stepCount = opacities.value.items.length;

        if ("List" === widths?.value?.kind && stepCount !== widths.value.items.length)
            this.error(widths.value, "Widths gives " + widths.value.items.length + " steps, but Opacities " + stepCount + ": give every step both.");

        const loop = find("Loop");
        let loopSteps: { first: number; last: number } | undefined;

        if (loop)
        {
            const items = "List" === loop.value?.kind ? loop.value.items : [];
            const [first, last] = items.map(item => "Integer" === item.kind ? item.value : Number.NaN);

            if (2 !== items.length || undefined === first || undefined === last || !(first <= last) || stepCount <= last)
            {
                this.error(loop.value ?? loop, "Loop takes its first and its last step among the " + stepCount + ", the first not after the last: Loop={ 1, 2 }.");
                return;
            }

            loopSteps = { first: first, last: last };
        }

        //Without a loop the last step is the ending. A section without steps ignores its time
        const sections: [string, number, string][] =
        [
            ["StartTime", loopSteps ? loopSteps.first : stepCount - 1, "a flash-up"],
            ["LoopTime", loopSteps ? 1 : 0, "a loop"],
            ["EndTime", loopSteps ? stepCount - loopSteps.last - 1 : 1, "an ending"]
        ];

        for (const [name, sectionStepCount, section] of sections)
        {
            if (0 < sectionStepCount && !find(name))
                this.error(element, "This <Flash> has " + section + ", so it needs " + name + " in milliseconds.");
        }
    }

    //A struct written with every field named, in their order: what the element gives, else the field's default.
    protected structLiteral(type: string, element: Element, consumed: Set<Attribute>): string | undefined
    {
        const structClass = this._schema.classes[type];

        if (!structClass)
            return undefined;

        this._headers.add(headerName(structClass.header));
        const fields: string[] = [];
        let isValid = true;

        for (const [name, field] of Object.entries(structClass.fields))
        {
            const attribute = element.attributes.find(candidate => name === candidate.name);
            let value: string | undefined;

            if (attribute)
            {
                consumed.add(attribute);

                //A track is a share of the Lasagna's size: Rows=4 is four tracks of 0.25.
                const isTracks = "AxisDefinition" === type && "std::vector<f32>" === field.type;

                if (isTracks && "Integer" === attribute.value?.kind)
                {
                    const count = Math.max(1, attribute.value.value);

                    if (0 >= attribute.value.value)
                        this.error(attribute.value, name + " takes at least one track.");

                    value = "{ " + Array.from({ length: count }, () => floatText(1 / count, true)).join(", ") + " }";
                }
                else
                {
                    value = this.convertAt(attribute, field.type, structClass.cpp);
                }

                const tracks = "List" === attribute.value?.kind ? attribute.value.items : [];
                const sum = tracks.reduce((total, item) => total + ("Integer" === item.kind || "Float" === item.kind ? item.value : 0), 0);

                if (isTracks && 0 < tracks.length && 1e-3 < Math.abs(sum - 1))
                    this.report(attribute.value, "warning", name + " adds up to " + Number(sum.toFixed(4)) + ": each track is a share of the Lasagna's size, so together they usually make 1.0.");
            }
            else if (undefined !== field.default)
            {
                value = this.convertText(field.default, field.type, structClass.cpp, element);
            }
            else
            {
                this.error(element, "<" + element.name + "> needs " + name + ", which " + type + " has no default for.");
            }

            if (undefined === value)
            {
                isValid = false;
                continue;
            }

            fields.push("." + field.member + " = " + value);
        }

        return isValid ? structClass.cpp + " { " + fields.join(", ") + " }" : undefined;
    }

    //Attributes: setters and signals

    //The C++ type the element's Type="F32" picks for its class's setter templates, its Type then taken. Else the fallback (a
    //prefab child's own Type, for an instance's entry). Undefined for a class without setter templates, whose Type is left
    //to be reported as unknown, and after an error
    protected valueTypeOf(schemaClass: SchemaClass, element: Element, consumed: Set<Attribute>, fallback?: string): string | undefined
    {
        if (!Object.values(schemaClass.setters).flat().some(overload => overload.template))
            return undefined;

        const attribute = element.attributes.find(candidate => "Type" === candidate.name);

        if (!attribute)
            return fallback;

        consumed.add(attribute);
        const value = attribute.value;
        const type = "String" === value?.kind ? valueTypes[value.value] : undefined;

        if (!type)
            this.error(value ?? attribute, "Type takes one of " + Object.keys(valueTypes).map(name => "\"" + name + "\"").join(", ") + ".");

        return type;
    }

    //The calls an element's attributes make on the target: its signals, then its setters, a group's attributes going
    //into one call (FontFamily="Arial" FontSize=18.0 is one SetFontFamily). valueType is the C++ type the setter
    //templates take (SetValue<f32>); without one they can't be used.
    protected attributeStatements(schemaClass: SchemaClass, elementName: string, attributes: readonly Attribute[], target: string, valueType?: string): Statement[]
    {
        const statements: Statement[] = [];
        const remaining = [...attributes];
        const take = (attribute: Attribute) => remaining.splice(remaining.indexOf(attribute), 1);

        for (const attribute of attributes.filter(candidate => /^On[A-Z]/.test(candidate.name)))
        {
            take(attribute);
            statements.push(...this.signalStatements(schemaClass, elementName, attribute, target));
        }

        for (const attribute of attributes.filter(candidate => "Flavors" === candidate.name))
        {
            take(attribute);
            this.error(attribute, "Flavors aren't generated yet.");
        }

        //RotateX, RotateY and RotateZ, in degrees, are one rotation: SetRotation(glm::vec3(x, y, z)), 0 for an axis left out.
        const rotateAttributes = attributes.filter(candidate => /^Rotate[XYZ]$/.test(candidate.name));
        const rotation = schemaClass.setters["Rotation"]?.find(overload => 1 === overload.params.length && "glm::vec3" === overload.params[0]?.type);

        if (0 < rotateAttributes.length)
        {
            rotateAttributes.forEach(take);
            const rotationAttribute = attributes.find(candidate => "Rotation" === candidate.name);

            if (!rotation)
                this.error(rotateAttributes[0], elementName + " doesn't turn.");
            else if (rotationAttribute)
                this.error(rotationAttribute, "Rotation and RotateX, RotateY or RotateZ can't both be set; use one way.");
            else
                statements.push(...this.rotationStatements(rotation.call, rotateAttributes, schemaClass, target));
        }

        //Groups first, the largest first, so FontSize goes into SetFontFamily when FontFamily is there too.
        const grouped = Object.entries(schemaClass.setters).flatMap(([name, overloads]) => overloads.filter(overload => overload.group && name === overload.group[0]).map(overload => ({ name: name, overload: overload })));
        grouped.sort((left, right) => (right.overload.group?.length ?? 0) - (left.overload.group?.length ?? 0));

        for (const { name, overload } of grouped)
        {
            const key = remaining.find(attribute => name === attribute.name);

            if (!key)
                continue;

            const members = (overload.group ?? []).map(member => remaining.find(attribute => member === attribute.name));
            members.forEach(member => member && take(member));
            const call = this.setterCall([overload], members, schemaClass, key);

            if (undefined !== call)
                statements.push({ text: target + call + ";", line: this.lineOf(key) });
        }

        for (const attribute of [...remaining])
        {
            take(attribute);
            const all = schemaClass.setters[attribute.setter] ?? [];
            const overloads = all.filter(overload => !overload.template && (!overload.group || attribute.setter === overload.group[0]));

            //A setter template takes the element's value type: SetValue<f32>(0.5f, false)
            if (valueType)
                overloads.push(...all.filter(overload => overload.template && !overload.group).map(overload => typedOverload(overload, valueType)));

            if (0 === overloads.length && all.some(overload => overload.template))
            {
                this.error(attribute, elementName + "'s " + attribute.name + " needs the value type first: Type=\"F32\" or another of " + Object.keys(valueTypes).join(", ") + ".");
                continue;
            }

            if (0 === overloads.length)
            {
                const group = Object.values(schemaClass.setters).flat().find(overload => overload.group?.includes(attribute.setter));
                this.error(attribute, group ? attribute.name + " goes with " + group.group?.[0] + "." : elementName + " has no " + attribute.name + ".");
                continue;
            }

            const call = this.setterCall(overloads, [attribute], schemaClass, attribute);

            if (undefined !== call)
                statements.push({ text: target + call + ";", line: this.lineOf(attribute) });
        }

        return statements;
    }

    //The rotation RotateX, RotateY and RotateZ give, as one call.
    private rotationStatements(call: string, attributes: readonly Attribute[], schemaClass: SchemaClass, target: string): Statement[]
    {
        const degrees: string[] = [];

        for (const axis of ["X", "Y", "Z"])
        {
            const attribute = attributes.find(candidate => "Rotate" + axis === candidate.name);
            const value = attribute ? this.convertAt(attribute, "f32", schemaClass.cpp) : "0.0f";

            if (undefined === value)
                return [];

            degrees.push(value);
        }

        return [{ text: target + call + "(glm::vec3(" + degrees.join(", ") + "));", line: this.lineOf(attributes[0] as Attribute) }];
    }

    //The first overload the values fit, as a call: SetColors(std::array { … }, RetroFuturaGUI::ColorState::Hover).
    private setterCall(overloads: readonly SchemaSetter[], attributes: readonly (Attribute | undefined)[], schemaClass: SchemaClass, at: Attribute): string | undefined
    {
        let firstError: ConversionError | undefined;

        for (const overload of overloads)
        {
            try
            {
                return overload.call + "(" + this.setterArguments(overload, attributes, schemaClass, at).join(", ") + ")";
            }
            catch (error)
            {
                if (!(error instanceof ConversionError))
                    throw error;

                firstError ??= error;
            }
        }

        this.error(firstError?.node ?? at, firstError?.message ?? at.name + " can't be set.");
        return undefined;
    }

    private setterArguments(overload: SchemaSetter, attributes: readonly (Attribute | undefined)[], schemaClass: SchemaClass, at: Attribute): string[]
    {
        const markupParameters = overload.params.filter(parameter => !parameter.isState && !isEmitSignal(parameter));
        const values = new Map<SchemaParameter, string>();
        const state = attributes.find(attribute => attribute?.state)?.state;

        if (state && !overload.params.some(parameter => parameter.isState))
            throw new ConversionError(at, at.setter + " has no color states.");

        if (overload.group)
        {
            let isOmitted = false;

            for (const [index, parameter] of markupParameters.entries())
            {
                const attribute = attributes[index];
                const fallback = overload.defaults?.[parameter.name];

                if (attribute && isOmitted)
                    throw new ConversionError(attribute, attribute.name + " needs " + overload.group[index - 1] + " too.");

                if (attribute)
                    values.set(parameter, this.convertNamed(attribute.value ?? trueValue(attribute), parameter.type, parameter.name, schemaClass.cpp));
                else if (undefined !== fallback)
                    values.set(parameter, this.convertText(fallback, parameter.type, schemaClass.cpp, at, true));
                else if (parameter.hasDefault)
                    isOmitted = true;
                else
                    throw new ConversionError(at, at.name + " needs " + (overload.group[index] ?? parameter.name) + " too.");
            }
        }
        else
        {
            const attribute = attributes[0] as Attribute;
            const value = attribute.value ?? trueValue(attribute);
            const required = markupParameters.filter(parameter => !parameter.hasDefault).length;

            const first = markupParameters[0] as SchemaParameter;

            if (1 === markupParameters.length)
            {
                values.set(first, this.convertNamed(value, first.type, first.name, schemaClass.cpp));
            }
            else if ("List" === value.kind && required <= value.items.length && markupParameters.length >= value.items.length)
            {
                value.items.forEach((item, index) =>
                {
                    const parameter = markupParameters[index] as SchemaParameter;
                    values.set(parameter, this.convertNamed(item, parameter.type, parameter.name, schemaClass.cpp));
                });
            }
            else if (0 === required && 0 < markupParameters.length)
            {
                values.set(first, this.convertNamed(value, first.type, first.name, schemaClass.cpp));
            }
            else
            {
                throw new ConversionError(value, attribute.name + " takes " + markupParameters.length + " values, written as a list.");
            }
        }

        const result: string[] = [];

        for (const parameter of overload.params)
        {
            if (parameter.isState)
                result.push(this.stateValue(state ?? "Enabled", at));
            else if (isEmitSignal(parameter))
                result.push("false"); //Markup never fires a signal.
            else if (values.has(parameter))
                result.push(values.get(parameter) as string);
            else
                break;
        }

        return result;
    }

    private stateValue(state: string, at: Attribute): string
    {
        const states = this._schema.enums["ColorState"];

        if (!states?.values.includes(state))
            throw new ConversionError(at, state + " isn't a color state: " + (states?.values ?? []).join(", ") + ".");

        return states.cpp + "::" + state;
    }

    //OnClick=Slots.Accept, or a list of them: one connection each.
    private signalStatements(schemaClass: SchemaClass, elementName: string, attribute: Attribute, target: string): Statement[]
    {
        const signal = schemaClass.signals[attribute.name];

        if (!signal)
        {
            this.error(attribute, elementName + " has no signal " + attribute.name + ".");
            return [];
        }

        const value = attribute.value;
        const targets = "List" === value?.kind ? value.items : value ? [value] : [];

        if (0 === targets.length)
            this.error(attribute, attribute.name + " connects to slots: " + attribute.name + "=Slots.Accept.");

        const argumentCount = signalArgumentCount(signal.slot);
        const statements: Statement[] = [];

        for (const item of targets)
        {
            const connection = this.connection(item, argumentCount);

            if (connection)
                statements.push({ text: target + signal.connect + "(" + connection.lambda + ", " + String(connection.isAsync) + ");", line: this.lineOf(item) });
        }

        return statements;
    }

    //A connection target the generator doesn't know, reported where it is.
    protected unknownTarget(value: Value, targets: string): void
    {
        this.error(value, "A signal connects to " + targets + ", not " + printSyntax(value).trim() + ".");
    }

    //Values

    //Name is the parameter's or the field's, which tells a file apart from other text; empty for neither
    protected convertAt(attribute: Attribute, type: string, owner: string, name = ""): string | undefined
    {
        try
        {
            return this.convertNamed(attribute.value ?? trueValue(attribute), type, name, owner);
        }
        catch (error)
        {
            if (!(error instanceof ConversionError))
                throw error;

            this.error(error.node ?? attribute, error.message);
            return undefined;
        }
    }

    //A parameter's value: a file for a parameter naming one, else as its type is written
    protected convertNamed(value: Value, type: string, name: string, owner: string): string
    {
        return isFileParameter(type, name) ? this.fileArgument(value) : this.convert(value, type, owner);
    }

    //A file the markup names, as the built app finds it, kept for the scene's file list. Named by a reference
    //(Assets.Images.Logo.svg, RetroFuturaGUI.Images.CloseIcon.svg) or by a path inside an asset folder ("Images/Logo.svg"),
    //looked up in the project's folders first, then in RetroFuturaGUI's Resources. A file that isn't there stops Generate,
    //so a misspelled name never shows as a missing image
    private fileArgument(value: Value): string
    {
        const file = this.findFile(value);
        this._files.set(file, assetKinds[path.extname(file).toLowerCase()]);
        return JSON.stringify(file);
    }

    private findFile(value: Value): string
    {
        //The build copies the project's asset folders into Assets/ and RetroFuturaGUI's Resources into Resources/
        const projectFolders = this._assetFolders.map(folder => path.join(this._folder, folder));
        const libraryFolder = path.join(this._folder, "RetroFuturaGUI", "Resources");
        const find = (folders: readonly string[], relative: string, copiedTo: string) => folders.some(folder => isFile(path.join(folder, relative))) ? copiedTo + "/" + relative : undefined;

        if ("Reference" === value.kind)
        {
            const [root, ...rest] = value.segments;

            if (("Assets" !== root && "RetroFuturaGUI" !== root) || 3 > value.segments.length)
                throw new ConversionError(value, "A file is named Assets.<folders>.<name>.<extension> or RetroFuturaGUI.<folders>.<name>.<extension>, such as Assets.Images.Logo.svg.");

            //The last two names are the file's name and extension, the ones before them its folders
            const relative = [...rest.slice(0, -2), rest.slice(-2).join(".")].join("/");
            const file = "Assets" === root ? find(projectFolders, relative, "Assets") : find([libraryFolder], relative, "Resources");

            if (!file)
                throw new ConversionError(value, "Assets" === root ? "None of the project's asset folders (" + this._assetFolders.join(", ") + ") has " + relative + "." : "RetroFuturaGUI's Resources have no " + relative + ".");

            return file;
        }

        if ("String" !== value.kind)
            throw new ConversionError(value, "This takes a file: a reference such as Assets.Images.Logo.svg, or a path inside an asset folder such as \"Images/Logo.svg\".");

        const relative = value.value.replace(/\\/g, "/");

        if (path.isAbsolute(relative) || relative.split("/").includes(".."))
            throw new ConversionError(value, "A file's path stays inside an asset folder, such as \"Images/Logo.svg\".");

        const file = find(projectFolders, relative, "Assets") ?? find([libraryFolder], relative, "Resources");

        if (!file)
            throw new ConversionError(value, "Neither the project's asset folders (" + this._assetFolders.join(", ") + ") nor RetroFuturaGUI's Resources have " + relative + ".");

        return file;
    }

    //A default from the schema, written as a .bechaml value: a field's ("Fixed", 1.0) or a setter's (Pixels, a bare enum
    //value). It's checked where the element is, since the mistake is the library's.
    private convertText(text: string, type: string, owner: string, at: Span, isBareWordEnum = false): string
    {
        const value = isBareWordEnum && /^[A-Za-z_]\w*$/.test(text) && this.findEnum(type, owner) ? JSON.stringify(text) : text;
        const parsed = parseBechamlValue(value);

        if (0 < parsed.diagnostics.length)
            throw new ConversionError(at, "The schema's default " + text + " for " + type + " isn't a value.");

        return this.convert({ ...parsed.value, start: at.start, end: at.start } as Value, type, owner);
    }

    //The value as C++ of the type the setter, field or constructor takes. Owner is the class the type is named in, so
    //DockingEdge in MenuBar is MenuBar::DockingEdge.
    protected convert(value: Value, type: string, owner: string): string
    {
        if ("Reference" === value.kind)
            throw new ConversionError(value, ("Dictionary" === value.segments[0] ? "Dictionary references" : "References such as " + value.segments.join(".")) + " aren't generated yet.");

        if ("bool" === type)
        {
            if ("Bool" !== value.kind)
                throw new ConversionError(value, "This takes True or False.");

            return String(value.value);
        }

        if (integerTypes.has(type))
        {
            if ("Integer" !== value.kind)
                throw new ConversionError(value, "This takes a whole number.");

            if (unsignedTypes.has(type) && 0 > value.value)
                throw new ConversionError(value, "This takes no negative number.");

            return String(value.value);
        }

        if ("f32" === type || "f64" === type || "float" === type || "double" === type)
            return floatText(numberOf(value), "f32" === type || "float" === type);

        if ("std::string_view" === type || "std::string" === type)
        {
            if ("String" !== value.kind)
                throw new ConversionError(value, "This takes a string.");

            return JSON.stringify(value.value);
        }

        if ("std::chrono::milliseconds" === type)
        {
            if ("Integer" !== value.kind)
                throw new ConversionError(value, "This takes whole milliseconds.");

            return "std::chrono::milliseconds(" + value.value + ")";
        }

        const vector = /^glm::vec([234])$/.exec(type);

        if (vector?.[1])
            return vectorText(value, Number(vector[1]));

        if ("std::span<const glm::vec4>" === type || "std::vector<glm::vec4>" === type)
        {
            const colors = colorList(value).map(color => vectorText(color, 4));
            this._headers.add("<array>");
            return "std::span<const glm::vec4>" === type ? "std::array { " + colors.join(", ") + " }" : "{ " + colors.join(", ") + " }";
        }

        if ("std::vector<f32>" === type || "std::span<const f32>" === type)
        {
            if ("List" !== value.kind)
                throw new ConversionError(value, "This takes a list of numbers: { 1.0, 2.0 }.");

            const numbers = value.items.map(item => floatText(numberOf(item), true));

            if ("std::vector<f32>" === type)
                return "{ " + numbers.join(", ") + " }";

            if (0 === numbers.length)
                return "std::span<const f32> {}";

            this._headers.add("<array>");
            return "std::array { " + numbers.join(", ") + " }";
        }

        const enumeration = this.findEnum(type, owner);

        if (enumeration)
        {
            if ("String" !== value.kind || !enumeration.values.includes(value.value))
                throw new ConversionError(value, "This takes one of " + enumeration.values.map(name => "\"" + name + "\"").join(", ") + ".");

            this._headers.add(enumeration.header.startsWith("../") ? "PlatformBridge.hpp" : headerName(enumeration.header));
            return enumeration.cpp + "::" + value.value;
        }

        throw new ConversionError(value, "A " + type + " can't be written in .bechaml yet.");
    }

    //The enum a type names, looked up as C++ would from the owner: in the owner and the classes around it, in its bases,
    //then in the library; else the one enum of that name nested anywhere.
    private findEnum(type: string, owner: string): { cpp: string; header: string; values: string[] } | undefined
    {
        const enums = this._schema.enums;
        const ownerKey = owner.replace(/^RetroFuturaGUI::/, "");
        const scopes: string[] = [];
        const addScopes = (key: string, seen: Set<string>) =>
        {
            if (seen.has(key))
                return;

            seen.add(key);
            const segments = key.split("::");

            for (let length = segments.length; 0 < length; --length)
                scopes.push(segments.slice(0, length).join("::"));

            for (const base of this._schema.classes[key]?.bases ?? [])
                addScopes(base.replace(/<.*>$/, ""), seen);
        };

        addScopes(ownerKey, new Set());

        for (const scope of scopes)
        {
            const found = enums[scope + "::" + type];

            if (found)
                return found;
        }

        if (enums[type])
            return enums[type];

        const nested = Object.entries(enums).filter(([key]) => key.endsWith("::" + type));
        return 1 === nested.length ? nested[0]?.[1] : undefined;
    }
}

//Writes C++ with #line directives, so what a compiler says about a statement lands on the .bechaml line it came from,
//and what comes from no markup line lands in the generated file again.
export class CppWriter
{
    private readonly _lines: string[] = [];
    private readonly _generatedFile: string;
    private readonly _markupFile: string;
    private _nextMarkupLine: number | undefined; //The markup line the next line counts as, while lines count as markup.

    constructor(generatedFile: string, markupFile: string)
    {
        this._generatedFile = slashed(generatedFile);
        this._markupFile = slashed(markupFile);
    }

    write(text: string, markupLine?: number): void
    {
        //An empty line belongs to nothing, so it doesn't switch.
        if (undefined === markupLine && undefined !== this._nextMarkupLine && "" !== text)
        {
            this._lines.push("#line " + (this._lines.length + 2) + " \"" + this._generatedFile + "\"");
            this._nextMarkupLine = undefined;
        }
        else if (undefined !== markupLine && markupLine !== this._nextMarkupLine)
        {
            this._lines.push("#line " + markupLine + " \"" + this._markupFile + "\"");
            this._nextMarkupLine = markupLine;
        }

        this._lines.push(text);

        if (undefined !== this._nextMarkupLine)
            ++this._nextMarkupLine;
    }

    writeAll(statements: readonly Statement[], indent: string): void
    {
        for (const statement of statements)
            this.write("" === statement.text ? "" : indent + statement.text, statement.line);
    }

    text(): string
    {
        return this._lines.join("\n") + "\n";
    }
}

//What Roux passes a built-in function a signal calls (OnClick=@ActualSlider.StepUp): true for each emitSignal, as the
//call answers what the user did. Undefined when it takes anything else, which markup can't give yet
export function builtInArguments(parameters: readonly SchemaParameter[]): string[] | undefined
{
    return parameters.every(isEmitSignal) ? parameters.map(() => "true") : undefined;
}

//A setter template as the value type makes it: SetValue<f32>, its T parameters f32
function typedOverload(overload: SchemaSetter, valueType: string): SchemaSetter
{
    const { template, ...rest } = overload;
    const parameters = template ?? [];
    return { ...rest, call: overload.call + "<" + valueType + ">", params: overload.params.map(parameter => parameters.includes(parameter.type) ? { ...parameter, type: valueType } : parameter) };
}

export function trueValue(attribute: Attribute): Value
{
    return { kind: "Bool", value: true, start: attribute.start, end: attribute.end, children: [] };
}

function numberOf(value: Value): number
{
    if ("Integer" !== value.kind && "Float" !== value.kind)
        throw new ConversionError(value, "This takes a number.");

    return value.value;
}

function floatText(value: number, isSingle: boolean): string
{
    const text = Number.isInteger(value) && 1e15 > Math.abs(value) ? value.toFixed(1) : String(Number(value.toPrecision(9)));
    return text + (isSingle ? "f" : "");
}

//glm::vec4(…) from a list of numbers, one number for every component, or for a vec4 a color.
function vectorText(value: Value, size: number): string
{
    if (4 === size && ("Color" === value.kind || ("List" === value.kind && isColorList(value))))
        return "glm::vec4(" + colorComponents(value).map(component => floatText(component, true)).join(", ") + ")";

    if ("Integer" === value.kind || "Float" === value.kind)
        return "glm::vec" + size + "(" + floatText(value.value, true) + ")";

    if ("List" === value.kind && size === value.items.length)
        return "glm::vec" + size + "(" + value.items.map(item => floatText(numberOf(item), true)).join(", ") + ")";

    throw new ConversionError(value, "This takes " + size + " numbers: { " + Array.from({ length: size }, () => "0.0").join(", ") + " }.");
}

function isColorList(value: Value): boolean
{
    return "List" === value.kind && (3 === value.items.length || 4 === value.items.length) && value.items.every(item => "Integer" === item.kind || "Float" === item.kind);
}

//A color from 0 to 1 per channel: #RRGGBB(AA), or 3 or 4 numbers, from 0 to 1 when any of them has a decimal point and
//from 0 to 255 otherwise.
function colorComponents(value: Value): number[]
{
    if ("Color" === value.kind)
        return [value.red, value.green, value.blue, value.alpha].map(channel => round(channel / 255));

    if ("List" !== value.kind || !isColorList(value))
        throw new ConversionError(value, "This takes a color: #RRGGBB, #RRGGBBAA or { 1.0, 0.5, 0.0, 1.0 }.");

    const isNormalized = value.items.some(item => "Float" === item.kind);
    const channels = value.items.map(item => numberOf(item) / (isNormalized ? 1 : 255));
    return (3 === channels.length ? [...channels, 1] : channels).map(round);
}

//One color, or a list of them: #FF0000 and { 1.0, 0.0, 0.0 } are one, { #FF0000, #00FF00 } two.
function colorList(value: Value): Value[]
{
    if ("Color" === value.kind || isColorList(value))
        return [value];

    if ("List" === value.kind && 0 < value.items.length)
        return [...value.items];

    throw new ConversionError(value, "This takes a color or a list of colors.");
}

function round(value: number): number
{
    return Number(value.toFixed(6));
}

//How many values a signal hands its slots: typename Signal<std::vector<std::string>, glm::vec2>::Slot hands two.
function signalArgumentCount(slotType: string): number
{
    const start = slotType.indexOf("Signal<");

    if (-1 === start)
        return 0;

    let depth = 0;
    let end = start + "Signal<".length;

    for (; slotType.length > end; ++end)
    {
        const character = slotType[end];

        if ("<" === character)
            ++depth;
        else if (">" === character && 0 === depth--)
            break;
    }

    const inner = slotType.slice(start + "Signal<".length, end).trim();
    return "" === inner ? 0 : splitTopLevel(inner).length;
}

//Splits at the commas that aren't inside <>, () or {}.
export function splitTopLevel(text: string): string[]
{
    const parts: string[] = [];
    let depth = 0;
    let current = "";

    for (const character of text)
    {
        if ("<({".includes(character))
            ++depth;
        else if (">)}".includes(character))
            --depth;

        if ("," === character && 0 === depth)
        {
            parts.push(current.trim());
            current = "";
            continue;
        }

        current += character;
    }

    parts.push(current.trim());
    return parts;
}

//OkButton is okButton, OKButton okButton, UI ui.
export function lowerFirst(name: string): string
{
    const capitals = /^[A-Z]+/.exec(name)?.[0] ?? "";

    if (1 >= capitals.length)
        return name.charAt(0).toLowerCase() + name.slice(1);

    const isWhole = capitals.length === name.length;
    const lowered = isWhole ? capitals.length : capitals.length - 1;
    return name.slice(0, lowered).toLowerCase() + name.slice(lowered);
}

export function upperFirst(name: string): string
{
    return name.charAt(0).toUpperCase() + name.slice(1);
}

export function headerName(header: string): string
{
    return path.posix.basename(header);
}

//With forward slashes and the drive letter in upper case, so the same file reads the same however the folder Roux was
//started in spells it (e:\ or E:\), and a Generate from another terminal changes nothing.
function slashed(file: string): string
{
    return file.split(path.sep).join("/").replace(/^([a-z]):/, (_match, drive: string) => drive.toUpperCase() + ":");
}
